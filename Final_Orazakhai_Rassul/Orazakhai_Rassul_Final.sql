DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'bookstore_readonly') THEN
        CREATE ROLE bookstore_readonly;
    END IF;
    
    IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'bookstore_writer') THEN
        CREATE ROLE bookstore_writer;
    END IF;
END
$$;


GRANT USAGE ON SCHEMA bookstore TO bookstore_readonly;
GRANT USAGE ON SCHEMA bookstore TO bookstore_writer;


