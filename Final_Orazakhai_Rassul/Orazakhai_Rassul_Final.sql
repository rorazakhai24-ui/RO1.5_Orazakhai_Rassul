-- =============== PART 1: CREATE ===============

CREATE SCHEMA IF NOT EXISTS bookstore;
SET search_path TO bookstore, public;


CREATE TABLE IF NOT EXISTS publishers (
    publisher_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publisher_name VARCHAR(100) NOT NULL,
    country VARCHAR(50) NOT NULL,
    contact_phone VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS suppliers (
    supplier_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name VARCHAR(100) NOT NULL UNIQUE,
    contact_phone VARCHAR(20) NOT NULL UNIQUE,
    supplier_email VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS authors (
    author_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS books (
    book_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publisher_id INT NOT NULL,
    supplier_id INT NOT NULL,
    isbn VARCHAR(13) UNIQUE,
    title VARCHAR(255) NOT NULL,
    price NUMERIC(6, 2) NOT NULL CHECK (price >= 0),
    published_date DATE NOT NULL CHECK (published_date > DATE '2026-01-01'),
    language VARCHAR(30) DEFAULT 'English',
    stock_status VARCHAR(20) DEFAULT 'In stock',
    FOREIGN KEY (publisher_id) REFERENCES publishers(publisher_id) ON DELETE RESTRICT,
    FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS book_author (
    book_id INT NOT NULL,
    author_id INT NOT NULL,
    PRIMARY KEY (book_id, author_id),
    FOREIGN KEY (book_id) REFERENCES books(book_id) ON DELETE CASCADE,
    FOREIGN KEY (author_id) REFERENCES authors(author_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS stores (
    store_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_name VARCHAR(100) NOT NULL,
    city VARCHAR(50) NOT NULL,
    date_opened DATE
);

CREATE TABLE IF NOT EXISTS employees (
    employee_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id INT,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    position VARCHAR(20) NOT NULL CHECK (position IN ('Manager', 'Cashier', 'Consultant', 'Storekeeper')),
    FOREIGN KEY (store_id) REFERENCES stores(store_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS inventory (
    store_id INT NOT NULL,
    book_id INT NOT NULL,
    stock_quantity INT NOT NULL CHECK (stock_quantity >= 0),
    last_restocked TIMESTAMP NOT NULL,
    PRIMARY KEY (store_id, book_id),
    FOREIGN KEY (store_id) REFERENCES stores(store_id) ON DELETE CASCADE,
    FOREIGN KEY (book_id) REFERENCES books(book_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS customers (
    customer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    phone VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS sales (
    sale_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id INT NOT NULL,
    employee_id INT NOT NULL,
    customer_id INT,
    sale_timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    tax_rate NUMERIC(3, 2) NOT NULL,
    total_amount NUMERIC(8, 2) NOT NULL,
    payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('Cash', 'Card', 'Mobile')),
  
  --(GENERATED ALWAYS AS)
	
    tax_paid_amount NUMERIC(8, 2) GENERATED ALWAYS AS (total_amount * tax_rate) STORED,
    FOREIGN KEY (store_id) REFERENCES stores(store_id) ON DELETE RESTRICT,
    FOREIGN KEY (employee_id) REFERENCES employees(employee_id) ON DELETE RESTRICT,
    FOREIGN KEY (customer_id) REFERENCES customers(customer_id) ON DELETE SET NULL
);

